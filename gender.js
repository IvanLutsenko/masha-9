// Род по имени — для «Дорогая Соня / Дорогой Прохор».
// Явно можно указать в ссылке: …/#Саша.ж или …/#Саша.м
window.Gender = (() => {
  const MALE_A = ["дима","миша","саша","никита","илья","лёва","лева","ваня","петя","коля","федя","гоша","кузьма","фома","муса","иса","яхья","мустафа","данила","савва","лука","тима","сеня","серёжа","сережа","лёша","леша","алёша","алеша","вова","слава","паша","гриша","боря","толя","рома","юра","витя","стёпа","степа","жора"];
  const FEMALE_SOFT = ["амаль","асель","айгуль","гуль","любовь","нинель","рахель","адель","мириам","зейнаб","айжан","меруерт","нурсулу","айсулу","аружан","толганай","жибек","карлыгаш"];
  function detect(raw){
    const n = (raw || "").trim().toLowerCase().split(/[\s-]/)[0];
    if (!n) return null;
    if (MALE_A.includes(n)) return "m";
    if (FEMALE_SOFT.includes(n)) return "f";
    if (/[ая]$/.test(n)) return "f";
    if (/[еэ]$/.test(n)) return "f";       // Сауле, Аделе
    if (/ь$/.test(n)) return "m";           // Игорь; женские мягкие — в списке выше
    return "m";                              // Прохор, Али, Алим-хан
  }
  // "Соня.ж" → {name:"Соня", g:"f"}
  function parse(hash){
    const m = hash.match(/^(.*?)(?:\.(ж|м|f|m))?$/i);
    const name = (m[1] || "").trim();
    const flag = (m[2] || "").toLowerCase();
    const g = flag ? (flag === "ж" || flag === "f" ? "f" : "m") : detect(name);
    return { name, g };
  }
  // форма по роду: pick(g, "приглашён", "приглашена", "приглашён(а)")
  const pick = (g, m, f, n) => g === "f" ? f : g === "m" ? m : n;
  return { detect, parse, pick };
})();
